"""Put a chosen sound into the project and record where it came from."""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import tempfile
import time
from pathlib import Path

from otohiroi import freesound, library, media, net

LEDGER = "sounds.license.json"
CREDITS = "CREDITS.md"
WIKIMEDIA_HOST = "https://upload.wikimedia.org/"
DEFAULT_LUFS = {"music": -20.0, "ambience": -24.0, "sfx": -16.0}
_UNSAFE = re.compile(r"[^\w\-]+")


class FetchError(Exception):
    pass


def _manual(sound: dict, reason: str) -> dict:
    return {"status": "manual_download_needed", "id": sound["id"], "title": sound["title"], "license": sound["license"],
            "page": sound.get("landing_url"), "reason": reason,
            "next_step": "Give the user the page link. After they download the file, register it with add_pack."}


def _obtain(sound: dict, workdir: Path) -> tuple[Path, str] | dict:
    """The audio in a working file and how good it is, or a manual_download_needed result."""
    if sound["id"].startswith("local:"):
        return library.file_of(sound), "as supplied"
    if sound["source"] == "freesound":
        key = freesound.api_key()
        if key is None:
            return _manual(sound, "Freesound's API terms forbid fetching its audio outside the API, and no "
                                  f"{freesound.KEY_ENV} is set. A free personal key is at {freesound.KEY_URL}.")
        if "freesound_id" not in sound:
            return _manual(sound, "Could not work out the Freesound id from its page address.")
        data, suffix, current = freesound.download_preview(sound["freesound_id"], key)
        if current is None or current != sound["license"]:
            raise FetchError(f"Freesound now reports license {current!r}, not {sound['license']!r}. Not downloaded.")
        path = workdir / f"download{suffix}"
        path.write_bytes(data)
        return path, "Freesound high quality preview (about 192 kbps ogg), not the original upload"
    url = sound.get("preview_url") or ""
    if sound["source"] == "wikimedia_audio" and url.startswith(WIKIMEDIA_HOST):
        path = workdir / f"download{Path(url.split('?')[0]).suffix.lower() or '.ogg'}"
        path.write_bytes(net.get_bytes(url))
        return path, "file hosted by Wikimedia Commons"
    return _manual(sound, f"Otohiroi has no permitted automatic route for {sound['source']}.")


def _filename(sound: dict, suffix: str) -> str:
    stem = _UNSAFE.sub("_", sound["title"]).strip("_")[:60] or "sound"
    tag = hashlib.sha1(sound["id"].encode()).hexdigest()[:6]
    return f"{stem}_{tag}{suffix}"


def _credit_line(entry: dict) -> str:
    link = f" <{entry['page']}>" if entry.get("page") else ""
    extra = "".join(f" {text}" for text in (
        "**Credit required.**" if entry["credit_required"] else "",
        "**Share-alike applies.**" if entry["share_alike"] else "",
        f"**Licensed for region: {entry['region']} only.**" if entry.get("region") else "",
    ) if text)
    return f"- `{entry['file']}`: \"{entry['title']}\" by {entry['author']} ({entry['license'].upper()}){link}{extra}"


def _record(dest: Path, entry: dict) -> None:
    ledger_path = dest / LEDGER
    entries = json.loads(ledger_path.read_text(encoding="utf-8")) if ledger_path.exists() else []
    entries = [old for old in entries if old["file"] != entry["file"]] + [entry]
    ledger_path.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = ["# Audio credits", "", "Generated by Otohiroi from sounds.license.json.", "",
             *(_credit_line(e) for e in entries), ""]
    (dest / CREDITS).write_text("\n".join(lines), encoding="utf-8")


def fetch(sound: dict, dest: str, format: str = "ogg", normalize: bool = True, trim_silence: bool | None = None,
          loudness_lufs: float | None = None, allow_warning: bool = False) -> dict:
    target_dir = Path(dest).expanduser()
    if not target_dir.is_absolute():
        raise FetchError("dest must be an absolute path.")
    if sound.get("warning") and not allow_warning:
        raise FetchError(f"{sound['warning']} Pass allow_warning=true only after the user has decided to take it.")
    target_dir.mkdir(parents=True, exist_ok=True)

    notes = []
    with tempfile.TemporaryDirectory() as temporary:
        obtained = _obtain(sound, Path(temporary))
        if isinstance(obtained, dict):
            return obtained
        working, quality = obtained
        keep_original = format == "original" or not media.available()
        if keep_original:
            if format != "original":
                notes.append("ffmpeg was not found, so the file was not converted or normalised.")
            output = target_dir / _filename(sound, working.suffix.lower())
            shutil.copyfile(working, output)
        else:
            output = target_dir / _filename(sound, f".{format}")
            trim = trim_silence if trim_silence is not None else (sound["kind"] == "sfx" and sound.get("loop") is not True)
            lufs = (loudness_lufs if loudness_lufs is not None else DEFAULT_LUFS[sound["kind"]]) if normalize else None
            media.convert(working, output, trim, lufs)
            if sound.get("loop") and normalize:
                notes.append("Tagged as a loop: listen to the seam after processing.")

    entry = {
        "file": output.name, "id": sound["id"], "title": sound["title"], "author": sound["author"],
        "source": sound["source"], "page": sound.get("landing_url"), "license": sound["license"],
        "license_url": sound.get("license_url"), "commercial_use": sound["commercial_use"],
        "credit_required": sound["credit_required"], "share_alike": sound["share_alike"], "region": sound.get("region"),
        "note": sound.get("note"), "quality": quality, "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "fetched": time.strftime("%Y-%m-%d"),
    }
    _record(target_dir, entry)
    if sound.get("region"):
        notes.append(f"This license only covers {sound['region']}. Distributing the game elsewhere is outside it.")
    if sound["credit_required"]:
        notes.append("The license requires credit: include CREDITS.md content in the game.")
    return {"status": "fetched", "path": str(output), "duration_s": media.duration_s(output), "license": sound["license"],
            "quality": quality, "ledger": str(target_dir / LEDGER), "notes": notes}
